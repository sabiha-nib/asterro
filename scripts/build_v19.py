"""Build the V19 products (offline; no network).
    python3 scripts/build_v19.py
Writes public/data/v19/{registry,sources,ml_validation}.json and app/frontend/phase4/data_v19.js (ASTERRO_V19).
  registry       asterro.v19.registry/1: nine states, V17 states mapped, V19 catalogue, last attempts (src/v19/registry.py)
  sources        asterro.v19.sources/1: the acquisition catalogue (src/v19/catalogue.py)
  site_samples   asterro.v19.site_samples/1: map units, volcanoes and biological records at 16 cells (src/v19/samples.py)
  ml_validation  asterro.v19.mlval/1: stability and sensitivity of the V17 patterns (src/v19/mlval.py), when computed
Acquired datasets add their own products under public/data/v19/ through their acquisition scripts."""
import hashlib, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.v19 import registry as R, catalogue as C, samples as SM  # noqa: E402


def main():
    out = os.path.join(ROOT, "public/data/v19"); os.makedirs(out, exist_ok=True)
    samples = SM.build()  # validates the site samples and writes their manifests before the registry reads them
    docs = {"registry": R.build(), "sources": C.build(), "site_samples": samples}
    mlp = os.path.join(ROOT, "data/v19/ml_validation.json")
    if os.path.exists(mlp):
        docs["ml_validation"] = json.load(open(mlp))
    shas = {}
    for k, d in docs.items():
        b = json.dumps(d, ensure_ascii=False, sort_keys=True, indent=1).encode()
        open(os.path.join(out, k + ".json"), "wb").write(b)
        shas[k] = hashlib.sha256(b).hexdigest()
    page = {"registry": docs["registry"], "ml_validation": docs.get("ml_validation"), "samples": samples, "sha256": shas}
    js = ("/* ===== V19 products (generated by scripts/build_v19.py; do not edit; edit src/v19/ and data/v19/) =====\n"
          " * Data Integration Registry (nine states) and ML validation. The same documents are in public/data/v19/. */\n"
          "const ASTERRO_V19 = " + json.dumps(page, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
    open(os.path.join(ROOT, "app/frontend/phase4/data_v19.js"), "w").write(js)
    print("data_v19.js", len(js), "bytes", docs["registry"]["counts"])


if __name__ == "__main__":
    main()
