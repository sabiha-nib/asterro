"""Build the extension data (developer tool; deterministic, offline).
    python3 scripts/build_ext.py
1. public/data/ext/thermal_ext.json  — tai-ext-thermal-1.0.0, recomputed from retained raw inputs (src/ext/thermal_absolute.py)
2. public/data/ext/{dimensions,processes,known_analogues,profiles_ext}.json — copied from data/ext/ (the structure files)
3. app/frontend/phase4/data_ext.js    — the same five documents embedded for the page (ASTERRO_EXT), with their SHA-256
"""
import hashlib, json, os, shutil, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.ext import thermal_absolute as TA

TA.build()
pub = os.path.join(ROOT, "public/data/ext")
docs, shas = {}, {}
for name in ["dimensions", "processes", "known_analogues", "profiles_ext"]:
    src = os.path.join(ROOT, "data/ext", name + ".json")
    shutil.copyfile(src, os.path.join(pub, name + ".json"))
    docs[name] = json.load(open(src))
docs["thermal"] = json.load(open(os.path.join(pub, "thermal_ext.json")))
for name in ["dimensions", "processes", "known_analogues", "profiles_ext", "thermal_ext"]:
    shas[name] = hashlib.sha256(open(os.path.join(pub, name + ".json"), "rb").read()).hexdigest()
js = ("/* ===== Extension data (generated by scripts/build_ext.py — do not edit; edit data/ext/*.json and src/ext/) =====\n"
      " * dimensions, processes, known analogue sites, extended mission profiles and the thermal-extremes values\n"
      " * (tai-ext-thermal-1.0.0). The same documents are published in public/data/ext/ with these SHA-256. */\n"
      "const ASTERRO_EXT = " + json.dumps({**docs, "sha256": shas}, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
open(os.path.join(ROOT, "app/frontend/phase4/data_ext.js"), "w").write(js)
print("data_ext.js", len(js), "bytes;", {k: v[:12] for k, v in shas.items()})
