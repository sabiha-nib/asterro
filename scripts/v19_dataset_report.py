"""Write docs/v19/DATASETS.md from the V19 registry and catalogue (no hand-edited states).
    python3 scripts/v19_dataset_report.py"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = json.load(open(os.path.join(ROOT, "public/data/v19/registry.json")))
S = {s["id"]: s["label"] for s in R["states"]}


def last(r):
    a = r.get("last_attempt")
    if not a:
        return "retained in ASTERRO" if r["state"].startswith("integrated") else "–"
    if isinstance(a, str):
        return a
    return f"{a['class']} ({a['utc']}): {a.get('error') or ('HTTP ' + str(a.get('http_status')))}"


def esc(s):
    if isinstance(s, dict):  # inventory versions recorded as HTTP metadata
        s = "; ".join(f"{k} {v}" for k, v in s.items())
    return str(s if s is not None else "–").replace("|", "\\|").replace("\n", " ")


out = ["# ASTERRO V19: dataset report", "",
       "Generated by `scripts/v19_dataset_report.py` from `public/data/v19/registry.json`; do not edit by hand.", "",
       "Integration state is decided only by retained, hashed files (V17 inventory or a V19 acquisition manifest). "
       "`access_blocked` means the build environment's egress proxy refused the connection, or the WebFetch service refused the route (robots.txt or URL length): neither says anything about the provider. "
       "Descriptions marked *unverified* come from published documentation and have not yet been checked against the provider.", "",
       "## Counts", "", "| State | Datasets |", "|---|---:|"]
out += [f"| {s['label']} | {R['counts'][s['id']]} |" for s in R["states"]]
out += ["", f"Total: {len(R['sources'])} datasets.", ""]
for title, pred in [("Integrated (retained and checksum-verified)", lambda r: r["state"].startswith("integrated")),
                    ("V19 acquisition catalogue (priority order)", lambda r: r.get("origin") == "v19_catalogue"),
                    ("Other candidates carried from V17", lambda r: r.get("origin") != "v19_catalogue" and not r["state"].startswith("integrated"))]:
    rows = sorted([r for r in R["sources"] if pred(r)], key=lambda r: (r.get("priority") or 9, r["id"]))
    out += [f"## {title}", "", "| Dataset | Provider | Identifier | Body | Access | State | Last attempt | Scientific contribution |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        acc = ", ".join(f"{x['kind']} ({x['auth']})" for x in r.get("routes", [])) or esc(r.get("license"))
        val = r.get("value") or r.get("validation") or "–"
        doc = " *(unverified)*" if r.get("doc_status") == "unverified" else ""
        out.append(f"| {esc(r.get('title') or r['id'])}{doc} | {esc(r.get('provider'))} | {esc(r.get('dataset_id'))} | {esc(r.get('body'))} | {esc(acc)} | {S[r['state']]} | {esc(last(r))} | {esc(val)} |")
    out.append("")
open(os.path.join(ROOT, "docs/v19/DATASETS.md"), "w").write("\n".join(out))
print(len(R["sources"]), "datasets written")
