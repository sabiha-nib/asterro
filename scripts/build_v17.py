"""Build the V17 analytical products (developer tool; deterministic, offline; needs numpy, scipy, scikit-learn).
    python3 scripts/build_v17.py
Writes public/data/v17/{cube,patterns,registry,modules,limits}.json and app/frontend/phase4/data_v17.js (ASTERRO_V17,
the same documents embedded for the page, with their SHA-256). Inputs are only files already retained in data/.
"""
import base64, hashlib, json, os, sys
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.v17 import features as F, novelty as N, ml as M, registry as R, modules as MOD, limits as L


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode("ascii")


def sha_file(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def cluster_name(c, feats):
    f = dict(zip(feats, c))
    t = f["t2m_mean_c"]; a = f["aridity"]; r = f["surface_roughness"]
    temp = "polar" if t < -10 else "cold" if t < 5 else "temperate" if t < 18 else "warm"
    wet = "arid" if a < 0.2 else "semi_arid" if a < 0.5 else "humid"
    rel = "high_relief" if r >= 200 else "moderate_relief" if r >= 50 else "low_relief"
    return [temp, wet, rel]


def main():
    v, feat = F.compute()
    n = int(v.sum())
    inputs = {p: sha_file(os.path.join(ROOT, p)) for p in ["data/raw/power_climatology.npz", "data/raw/modis_lst.npz",
              "data/predictor_stack.npz", "data/ext/known_analogues.json", "public/data/ext/context_ext.json"]}
    cube = {"schema": "asterro.v17.cube/1", "version": F.VERSION, "n_cells": n, "missing": F.MISSING,
            "inputs_sha256": inputs, "vars": {}}
    for k, (sc, off) in F.QUANT.items():
        cube["vars"][k] = {"scale": sc, "offset": off, "unit": F.UNITS[k], "b64": b64(F.quantise(feat[k], sc, off))}
    cube["classes"] = {"aridity_class": F.ARIDITY_CLASSES, "landform_class": F.LANDFORM_CLASSES}
    cube["summary"] = F.summary(feat)
    nv = N.compute()
    up = np.where(np.isfinite(nv["uniqueness_pct"]), np.round(nv["uniqueness_pct"]), 255).astype(np.uint8)
    ep = np.where(np.isfinite(nv["known_env_pct"]), np.round(nv["known_env_pct"]), 255).astype(np.uint8)
    km = np.minimum(254, np.round(nv["known_km"] / 40)).astype(np.uint8)
    mlr = M.compute(feat)
    from scipy.stats import rankdata
    an = mlr["anomaly"]; f = np.isfinite(an)
    ap = np.full(n, 255, dtype=np.uint8)
    ap[f] = np.round((rankdata(an[f]) - 1) / (f.sum() - 1) * 100).astype(np.uint8)
    patterns = {"schema": "asterro.v17.patterns/1",
                "novelty": {"version": N.VERSION, "classes": N.CLASSES, "k": N.K, "radius_km": N.RADIUS_KM,
                            "criteria": N.CRIT, "site_cells": nv["site_cells"],
                            "uniqueness_pct_b64": b64(up), "known_env_pct_b64": b64(ep), "known_km40_b64": b64(km),
                            "class_b64": b64(nv["cls"].astype(np.uint8)),
                            "counts": {c: int((nv["cls"] == k).sum()) for k, c in enumerate(N.CLASSES)}},
                "ml": {"version": M.VERSION, "sklearn": mlr["sklearn"], "features": mlr["features"],
                       "k": mlr["kbest"], "silhouette": mlr["silhouette"], "agreement_koppen": mlr["agree"],
                       "spearman_isolation_vs_knn": mlr["spearman_if_knn"], "anomaly_p98": mlr["anomaly_p98"],
                       "complete_cells": mlr["complete"], "sizes": mlr["sizes"], "centers": mlr["centers"],
                       "names": [cluster_name(c, mlr["features"]) for c in mlr["centers"]],
                       "labels_b64": b64(mlr["labels"]), "anomaly_pct_b64": b64(ap),
                       "hidden_cells": [int(i) for i in np.flatnonzero(mlr["hidden"])],
                       "params": {"kmeans": {"n_init": 10, "random_state": 0, "k_range": [6, 12], "silhouette_sample": "every 20th complete cell"},
                                  "isolation_forest": {"n_estimators": 300, "max_samples": 4096, "random_state": 0},
                                  "hidden": "top 2 % anomaly and every |z| < 2"}}}
    pub = os.path.join(ROOT, "public/data/v17"); os.makedirs(pub, exist_ok=True)
    docs = {"cube": cube, "patterns": patterns, "registry": R.build(), "modules": MOD.build(), "limits": L.build()}
    shas = {}
    for k, d in docs.items():
        p = os.path.join(pub, k + ".json")
        json.dump(d, open(p, "w"), ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        shas[k] = sha_file(p)
    js = ("/* ===== V17 analytical products (generated by scripts/build_v17.py; do not edit; edit src/v17/ and data/v17/) =====\n"
          " * Feature cube (tai-v17-features), novelty and patterns (tai-v17-novelty, tai-v17-ml), Data Integration Registry,\n"
          " * domain modules and the Earth limitations framework. The same documents are in public/data/v17/ with these SHA-256. */\n"
          "const ASTERRO_V17 = " + json.dumps({**docs, "sha256": shas}, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
    open(os.path.join(ROOT, "app/frontend/phase4/data_v17.js"), "w").write(js)
    print("data_v17.js", len(js), "bytes", {k: v[:12] for k, v in shas.items()})
    print("k", mlr["kbest"], "agree", mlr["agree"], "rho", round(mlr["spearman_if_knn"], 3), "hidden", int(mlr["hidden"].sum()))


if __name__ == "__main__":
    main()
