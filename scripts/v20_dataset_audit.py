"""Write docs/v20/DATASET_AUDIT.md: every dataset in the inventory with eight precise statuses.

    python3 scripts/v20_dataset_audit.py

Statuses (yes / no), from public/data/v19/env/inventory.json and public/data/app.json only, so the audit cannot drift:
  Discovered          an official record or page was located (state DISCOVERED)
  Metadata verified   provider metadata was read and checked: a CMR collection record, or an answering endpoint (ACCESSIBLE)
  Downloaded          bytes were retrieved and kept with a SHA-256 (DOWNLOADED)
  Parsed              the file was parsed into ASTERRO's grid or tables (PROCESSED)
  Validated           automated checks passed (VALIDATED: hashes, units, bounds, overlaps, cross-checks)
  Integrated          the data are used by a view of the app (INTEGRATED)
  Used in calculation which calculation: the six-dimension similarity engine (Earth predictor or target value), the data-layer
                      analyses (Science domains, Local Impact), or none (context only / not obtained)
  Available offline   stored by the service worker and/or IndexedDB (CACHED)
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I = json.load(open(os.path.join(ROOT, "public/data/v19/env/inventory.json"), encoding="utf-8"))
APP = json.load(open(os.path.join(ROOT, "public/data/app.json"), encoding="utf-8"))
ROLE = {d["id"]: d["role"] for d in APP["datasets"]}
ENGINE = {"v19_nasa_power": "nasa_power", "v19_modis_aqua_lst": "modis_aqua_lst", "v19_gmted2010": "gmted2010", "v19_mola": "mola", "v19_dem_mars": "mola",
          "v19_lola": "lola", "v19_dem_moon": "lola", "v19_meda": "meda", "v19_diviner": "diviner", "v19_diviner_polar": "diviner"}
LAYER_EXTRA = {"gvp_holocene_full", "gvp_pleistocene", "macrostrat_sites", "gbif_sites", "usgs_mrds"}


def use(r):
    if r["id"] in ENGINE:
        role = ROLE.get(ENGINE[r["id"]], "")
        return "engine: " + ("Earth predictor" if "Earth" in role else "target value")
    if r["state"] in ("BLOCKED", "REQUIRES_AUTHENTICATION", "NOT_INVESTIGATED"):
        return "no (not obtained)"
    if r.get("cube_variables") or r["id"] in LAYER_EXTRA:
        return "data-layer analyses"
    if "INTEGRATED" in r["states"]:
        return "V19 domain views or context (not the score)"
    return "no"


cols = ["Discovered", "Metadata verified", "Downloaded", "Parsed", "Validated", "Integrated", "Used in calculation", "Available offline"]
def row(r):
    s = set(r["states"]); y = lambda b: "yes" if b else "no"
    meta = "ACCESSIBLE" in s or (r["id"].startswith("cmr_") and "DISCOVERED" in s)
    return [y("DISCOVERED" in s), y(meta), y("DOWNLOADED" in s), y("PROCESSED" in s), y("VALIDATED" in s), y("INTEGRATED" in s), use(r), y("CACHED" in s)]


rows = I["rows"]; R = [(r, row(r)) for r in rows]
tot = {c: sum(1 for _, v in R if v[k] == "yes") for k, c in enumerate(cols) if c != "Used in calculation"}
uses = {}
for _, v in R: uses[v[6]] = uses.get(v[6], 0) + 1
esc = lambda s: str(s if s is not None else "–").replace("|", "\\|").replace("\n", " ")
out = ["# ASTERRO V20: dataset status audit", "",
       f"Generated by `scripts/v20_dataset_audit.py` from `public/data/v19/env/inventory.json` ({I['n']} datasets, {I['nasa']} NASA) and `public/data/app.json`.",
       "Each status is yes only when the inventory records the evidence for it. Nothing here is estimated.", "",
       "## Totals", "", "| Status | Datasets with yes |", "|---|---|"] + [f"| {c} | {n} |" for c, n in tot.items()] + ["",
       "| Used in calculation | Datasets |", "|---|---|"] + [f"| {k} | {n} |" for k, n in sorted(uses.items(), key=lambda x: -x[1])] + ["",
       "Notes:", "",
       "- The six-dimension engine uses three Earth predictors (NASA POWER, MODIS Aqua LST, GMTED2010) and the target records built from MOLA, LOLA, MEDA and Diviner. "
       "Its inputs are unchanged in V20. NASA POWER and MODIS Aqua LST carry the V19 registry state `integrated_awaiting_validation`, so they show Validated = no here: "
       "they are verified by checksum against the published stack, but the V19 registry did not record an independent re-validation of the original downloads.",
       "- Data-layer analyses (Science domains, Local Impact) read the V19 environmental cube, the volcano lists, the site queries and, new in V20, the USGS MRDS catalogue. "
       "They never change a similarity score.",
       "- Rows marked BLOCKED or REQUIRES_AUTHENTICATION were not obtained. No value is shown for them anywhere in the app.", "",
       "## Every dataset", "", "| Dataset | Agency | Headline state | " + " | ".join(cols) + " |", "|" + "---|" * (3 + len(cols))]
for r, v in R:
    out.append(f"| {esc(r.get('name'))} | {esc(r.get('agency'))} | {r['state']} | " + " | ".join(v) + " |")
os.makedirs(os.path.join(ROOT, "docs/v20"), exist_ok=True)
open(os.path.join(ROOT, "docs/v20/DATASET_AUDIT.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("docs/v20/DATASET_AUDIT.md", len(R), "rows", tot, uses)
